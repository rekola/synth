#!/usr/bin/env python3
"""Writes plans/modern-look-tokens.md from tokens.py's output.

    python3 tools/modern_look/tokens.py tokens.json > report.txt
    python3 tools/modern_look/tokens_doc.py tokens.json report.txt plans/modern-look-tokens.md"""
import json, sys

t = json.load(open(sys.argv[1]))
report = open(sys.argv[2]).read()
sh = t['shared']
rows = [('surface.base', 'The window and the quietest areas'), ('surface.panel', 'Panels: outline, scopes, clip slots, pattern editor'),
        ('surface.raised', 'Headings, bar rows'), ('surface.overlay', 'Floating layers (the command candidates, dialogs)'),
        ('text.primary', 'Data, headings, the thing being read'), ('text.secondary', 'Labels, units, empty cells next to data'),
        ('text.disabled', 'Placeholders, off flags, unset cells (UI-glyph contrast)'), ('accent', 'Cursor, region, focus, selected item'),
        ('accent.dim', 'Unfocused cursor, selected row tone'), ('text.on-accent', 'Text on the accent')]
md = '''# Modern look: colour tokens

The values behind `plans/modern-look.md` step 2, mocked in
`plans/modern-look-mock.html`. They come from `tools/modern_look/tokens.py`,
which holds the OKLCH source, converts to sRGB and checks the contrast rules;
this file is written from its output by `tools/modern_look/tokens_doc.py`.
Change the values in `tokens.py` and re-run both. `Theme::dark()` and
`Theme::light()` (`lib/cellui/include/cellui/Theme.h`) hold these values;
today's look is kept as `Theme::original()`. Roles the tables do not list
(cursor tints, command and reader text, track flags, locators, buttons, the
spectrum) take values derived from them there.

## Per theme

Neutrals are slightly cool (hue 250). Surfaces step in lightness, not in
lines: base, panel, raised, overlay. The steps are about 0.04-0.05 of OKLCH
lightness in both themes, which is what keeps the areas distinguishable
without lines; the light theme was first built with steps of 0.03 and read as
low contrast.

| Token | Dark | Light | Used for |
|---|---|---|---|
'''
for k, u in rows:
    md += f"| `{k}` | `{t['dark'][k]}` | `{t['light'][k]}` | {u} |\n"
md += f'''
## Shared with the Launchpad: one value in every theme

The Launchpad is always dark, has no icons, and has to show the same colours
as the screen, so a clip's colour and state cannot differ between a dark and a
light theme. These tokens therefore have **one value**. One lightness, OKLCH L
about 0.585-0.6, is at least 3:1 against the darkest surface and the light
theme's panel, so a single colour works on both.

| Token | Value | Meaning |
|---|---|---|
| `state.playing` | `{sh['state.playing']}` | The fill of a whole clip slot while it is playing **or queued to play**, as the whole pad turns green. Playing pulses and queued flashes, on the pads and in the terminal alike (`statePulse()` in `ClipGrid.cpp`: a one-second pulse between the colour and a shade 60% darker, a 250 ms flash); the glyph (`▸`, `▹`) tells them apart where there is no motion. Hue 145, the Launchpad's green. |
| `state.playing.dim` | `{sh['state.playing.dim']}` | Launched while the transport is paused. Same hue, little chroma. |
| `state.recording` | `{sh['state.recording']}` | The fill of a slot while recording **or queued to record**. Hue 27, the Launchpad's red. |
| `state.recording.dim` | `{sh['state.recording.dim']}` | An armed track's empty slot, or a take queued to stop. |
| `text.on-track` | `{sh['text.on-track']}` | Text on a track or state colour, in both themes. |
| `data.heat` | `{sh['data.heat']}` | The DirAC heatmap's fixed hue (not a Launchpad matter, listed with the rest of the colours that have no light variant). |

There is deliberately no separate "queued" token: a queued clip uses the
playing colour (or the recording one), as it does on the pads. The hues are
those of the Launchpad's clip states; the exact RGB of its palette entries
(`LaunchpadManager.cpp`: green 21 and 23, red 5 and 7) is not in this
repository, so only the hue is matched here, and a pad's brightness is the
hardware's own.

### Track colours

The same eight in both themes, from one formula: OKLCH L 0.585, C 0.12, the hue
stepped by the golden ratio over the hue arcs the two state colours leave
free (45-105 and 180-340 degrees), so a track never looks like a playing or a
recording clip, and the pads can tell the two apart without icons.

| Track | Hue | Colour |
|---|---|---|
'''
for i in range(8):
    md += f"| {i} | {sh['track_hues'][i]} | `{sh['tracks'][i]}` |\n"
md += '''
Where a track colour is under text (a placed arrangement block, a clip
number) the text is `text.on-track`. The Launchpad takes the same colours,
quantized to what the pads can show.

The level meter ramp, quiet to loud, is the same in both themes too (it is a
green-to-red scale, separate from the clip states): ''' + ', '.join(f"`{c}`" for f, c in sh['meter']) + '''.

## Contrast, measured

Generated by `tools/modern_look/tokens.py`: WCAG contrast ratio of each pair,
against the stated minimum (4.5 body text, 3.0 UI glyphs and blocks). The
shared colours are checked against both themes' surfaces.

```
''' + report + '''```

Not yet covered: a high-contrast theme (step 5), the heatmap and spectrum
colours, and the 256-colour fallback, which maps each token to the nearest
palette entry by perceptual distance (OKLab), not RGB.
'''
open(sys.argv[3], 'w').write(md)
